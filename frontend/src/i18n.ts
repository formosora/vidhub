/**
 * Tiny reactive i18n — no runtime dependency beyond Vue's own reactivity.
 *
 * `t()` reads `locale`, so every template that calls it re-renders on switch.
 * Keys mirror the server catalogue in server/lib/i18n.js where they overlap,
 * which is what lets the admin log render old rows in the current language.
 */
import { ref, watch } from 'vue'

export type Locale = 'zh' | 'en'
export const LOCALES: { id: Locale; label: string }[] = [
  { id: 'zh', label: '中文' },
  { id: 'en', label: 'English' },
]

const KEY = 'vidhub_lang'

function detect(): Locale {
  const saved = localStorage.getItem(KEY)
  if (saved === 'zh' || saved === 'en') return saved
  return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export const locale = ref<Locale>(detect())

export function setLocale(l: Locale) {
  locale.value = l
  localStorage.setItem(KEY, l)
}

watch(locale, l => { document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en' }, { immediate: true })

/** Every request carries the UI language so API errors come back translated. */
export const langHeader = () => ({ 'Accept-Language': locale.value === 'zh' ? 'zh-CN' : 'en' })

