/** Translate `key`, substituting {0}, {1}, … Unknown keys return the key. */
export function t(key: string, ...params: (string | number)[]): string {
  const row = D[key]
  if (!row) return key
  const s = (locale.value === 'en' ? row[1] : row[0]) ?? row[0]
  return s.replace(/\{(\d+)\}/g, (m, i) => String(params[Number(i)] ?? m))
}

